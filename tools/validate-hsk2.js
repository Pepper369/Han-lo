const hsk2Set = new Set();

for (const row of HSK2) {
  assert.strictEqual(row.length, 4, "Hàng phải đủ 4 trường: " + JSON.stringify(row));
  const [h, p, hv, vi] = row;
  assert.ok(!hsk1Set.has(h), "Trùng với HSK 1: " + h);
  assert.ok(!hsk2Set.has(h), "Trùng lặp trong HSK 2: " + h);
  hsk2Set.add(h);

  assert.ok(/^[a-zāáǎàēéěèīíǐìōóǒòūúǔùǖǘǚǜüńňǹr ]+$/i.test(p), "Pinyin không hợp lệ: " + h + " " + p);
  const tones = Core.syllables(p).map(Core.toneOf);
  assert.ok(tones.every(n => n >= 0 && n <= 4), "Dấu thanh lạ: " + h + " " + p);
  const neutralOnly = new Set(["啊", "地", "过"]);
  if (!neutralOnly.has(h)) {
    assert.ok(tones.some(n => n > 0), "Thiếu thanh điệu: " + h + " " + p);
  } else {
    assert.ok(tones.every(n => n === 0), "Phải là thanh nhẹ: " + h + " " + p);
  }
}

